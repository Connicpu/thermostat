#!/usr/bin/env python3
"""Generate 1-bpp bitmap fonts for the e-paper UI from DejaVu Sans Bold.
Usage: tools/gen_font.py > components/display/font_data.c
Char 127 is rendered as the degree sign."""
from PIL import Image, ImageDraw, ImageFont
import sys
TTF = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

def gen(name, px, chars):
    f = ImageFont.truetype(TTF, px)
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs, data = [], []
    for code in range(32, 128):
        ch = chr(code) if code != 127 else "\u00b0"
        if chr(code) not in chars and not (code == 127 and "\u00b0" in chars):
            glyphs.append((0, 0)); continue
        w = max(1, int(round(f.getlength(ch))))
        im = Image.new("1", (w, h), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=1)
        off = len(data)
        bpr = (w + 7) // 8
        for y in range(h):
            row = [0] * bpr
            for x in range(w):
                if im.getpixel((x, y)): row[x // 8] |= 0x80 >> (x % 8)
            data += row
        glyphs.append((w, off))
    out = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i+24]) + ",")
    out.append("};")
    out.append(f"static const font_glyph_t {name}_glyphs[96] = {{")
    out += [f"    {{{w}, {o}}}," for w, o in glyphs]
    out.append("};")
    out.append(f"const font_t {name} = {{ .height = {h}, .glyphs = {name}_glyphs, .bits = {name}_bits }};")
    return "\n".join(out)

print("/* Generated by tools/gen_font.py from DejaVu Sans Bold - do not edit. */")
print('#include "font.h"')
ascii_all = "".join(chr(c) for c in range(32, 127)) + "\u00b0"
print(gen("font_small", 15, ascii_all))
print(gen("font_med", 24, ascii_all))
print(gen("font_big", 48, " -.0123456789\u00b0CF"))
