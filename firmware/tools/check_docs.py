#!/usr/bin/env python3
"""Doc-comment check for our C code (README "Code style"). Needs `pip install libclang`.

Every struct definition and every function in our sources (same scope as check_naming.py)
must be preceded by a Doxygen block comment: `/** ... */` (a one-liner `/** ... */` is fine),
with only blank lines between the comment and the declaration.
  * public functions: the prototype in the header carries the full doc; the definition in
    the .c needs at least a brief one;
  * static functions: the definition carries the doc (forward declarations are exempt);
  * functions generated by one of our own macros (e.g. MK(...) in the HOOTL fakes): the
    doc goes on that macro's #define instead;
  * struct definitions, named or typedef'd (structs nested in another struct or local to a
    function body are covered by the comments of the outer one).
Exit 1 on any missing comment.

Usage: check_docs.py [--root DIR] [--db compile_commands.json ...]"""
import argparse, json, os, re, sys
import clang.cindex as ci
from clang.cindex import CursorKind as CK
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import check_naming as cn

def preceding_doc(lines, lineno):
    """True if the code on 1-based line `lineno` is preceded by a /** ... */ block (blank lines allowed)."""
    i = lineno - 2
    while i >= 0 and not lines[i].strip():
        i -= 1
    if i < 0 or not lines[i].rstrip().endswith("*/"):
        return False
    while i >= 0 and "/*" not in lines[i]:
        i -= 1
    return i >= 0 and lines[i][lines[i].rindex("/*"):].startswith("/**")

def decl_line(c):
    """First line of the declaration including `typedef` / storage class (libclang starts struct extents at `struct`)."""
    return c.extent.start.line

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap.add_argument("--db", action="append", default=[])
    a = ap.parse_args(argv)
    cn.setup(a.root, a.db)
    idx, done, covered, sibling = ci.Index.create(), set(), set(), {}
    missing, macros, text = {}, {}, {}
    dbs = [d for d in cn.DBS if os.path.exists(d)]
    if not dbs:
        sys.exit("no compile_commands.json: build test/host and test/hootl first")

    def src_lines(f):
        if f not in text:
            text[f] = cn.rd(f).splitlines()
        return text[f]

    def visit(tu):
        for inc in tu.get_includes():
            covered.add(os.path.realpath(inc.include.name))
        for c in tu.cursor.walk_preorder():
            if c.location.file is None: continue
            f = os.path.realpath(c.location.file.name)
            if not cn.ours(f): continue
            if c.kind == CK.MACRO_DEFINITION:
                macros[c.spelling] = (f, c.location.line)
                continue
            if c.kind == CK.FUNCTION_DECL:
                if not c.is_definition() and (f.endswith(".c") or c.storage_class == ci.StorageClass.STATIC):
                    continue                     # forward declaration in a .c / static prototype
            elif c.kind == CK.STRUCT_DECL:
                if not c.is_definition(): continue
                p = c.semantic_parent
                if p is not None and p.kind in (CK.STRUCT_DECL, CK.UNION_DECL, CK.FUNCTION_DECL): continue
            else:
                continue
            line = decl_line(c)
            ls = src_lines(f)
            first = re.match(r"\s*([A-Za-z_]\w*)\s*\(", ls[line - 1])
            if first and first.group(1) != c.spelling and first.group(1) in macros:
                f, line = macros[first.group(1)]      # generated by our macro: doc goes on the #define
                ls = src_lines(f)
            elif c.kind == CK.STRUCT_DECL and line >= 2 and ls[line - 1].lstrip().startswith("struct") \
                    and ls[line - 2].rstrip().endswith("typedef"):
                line -= 1
            if not preceding_doc(ls, line):
                kind = "struct" if c.kind == CK.STRUCT_DECL else "function"
                name = c.spelling or c.type.spelling
                missing.setdefault((f, line), (f[len(cn.ROOT) + 1:], line, kind, name))

    for db in dbs:
        for e in json.loads(cn.rd(db)):
            src = os.path.realpath(os.path.join(e["directory"], e["file"]))
            if not cn.ours(src) or (db, src) in done: continue
            done.add((db, src))
            args, _ = cn.clean_args(e, src)
            sibling.setdefault(os.path.dirname(src), args)
            sibling.setdefault(None, args)
            covered.add(src)
            visit(idx.parse(src, args, options=ci.TranslationUnit.PARSE_DETAILED_PROCESSING_RECORD))
    for f in cn.our_files():
        if f in covered: continue
        args = sibling.get(os.path.dirname(f)) or sibling.get(os.path.dirname(os.path.dirname(f))) or sibling[None]
        visit(idx.parse(f, (["-x", "c"] if f.endswith(".h") else []) + args + ["-I" + os.path.dirname(f)],
                        options=ci.TranslationUnit.PARSE_DETAILED_PROCESSING_RECORD))
    for f, line, kind, name in sorted(missing.values()):
        print(f"{f}:{line}: {kind} '{name}' has no preceding /** ... */ doc comment")
    print(f"check_docs: {len(missing)} missing doc comment(s)")
    return 1 if missing else 0

if __name__ == "__main__":
    sys.exit(main())
